import { test, expect } from "@playwright/test";
import { tinyPng, fakeImageBytes } from "../../api/helpers/images";
import { adminContext } from "../../api/helpers/auth";
import { createPost } from "../../api/helpers/fixtures";
import { loginAsAdmin } from "../helpers/auth";

const FILE_KEY = "e2e-admin-media";

// Makes CP-16b's own ad-hoc Playwright verification (described in prose in CHANGE-PLAN.md —
// "uploaded one valid PNG and one invalid .txt together through the actual file input, grid
// count 5->6, failed file's name listed, deleted through the real ConfirmModal, count 6->5")
// a permanent spec instead of a one-off manual check.

test.describe("admin media: real file upload, failed-filename list, delete via ConfirmModal", () => {
  test.beforeEach(async ({ page }) => {
    await loginAsAdmin(page);
    await page.goto("/admin/media");
  });

  test("uploading a valid image and an invalid file together: grid grows by one, the bad one is listed", async ({
    page,
  }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();

    const validName = `e2e-media-valid-${Date.now()}.png`;
    const invalidName = `e2e-media-invalid-${Date.now()}.png`;

    // The media grid's display name is now a cosmetically generated string (media.displayName,
    // generated by StorageService), unrelated to the uploaded filename — the only successful POST response's
    // body gives us the real row id to locate its card by afterward.
    const [uploadResponse] = await Promise.all([
      page.waitForResponse(
        (res) => res.url().includes("/api/v1/media") && res.request().method() === "POST" && res.ok()
      ),
      page.locator('input[type="file"]').setInputFiles([
        { name: validName, mimeType: "image/png", buffer: await tinyPng() },
        // Declares image/png but isn't decodable — StorageService.uploadImage rejects it with a
        // clean 400 once sharp fails to decode it (the 2026-09-28 hardening), surfacing here as a
        // failed-filename entry, not a silent drop.
        { name: invalidName, mimeType: "image/png", buffer: fakeImageBytes() },
      ]),
    ]);
    const uploadedId = (await uploadResponse.json()).data.id as string;

    await expect(grid).toHaveCount(before + 1, { timeout: 15_000 });
    await expect(page.getByText(invalidName)).toBeVisible();

    // Clean up the one real row this test created.
    const newCard = page.getByTestId(`media-card-${uploadedId}`);
    await newCard.locator("button").click();
    await page.getByTestId("confirm-modal-confirm").click();
    await expect(grid).toHaveCount(before, { timeout: 15_000 });
  });

  test("uploading several valid images at once grows the grid by all of them", async ({ page }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();

    const stamp = Date.now();
    // Kept modest (5), not a larger "bulk" number: RATE_LIMITS.upload is 30/minute
    // (src/utils/rateLimit.ts), and in `next dev` with no X-Forwarded-For header,
    // getClientKey() falls back to the single literal key "unknown" — every e2e test in the
    // whole run that POSTs to /media shares that one bucket (the same shared-bucket risk
    // tests/api/comments.spec.ts already hit in phase 1). 5 requests here, on top of the 2 the
    // file's other test already makes, stays comfortably under the limit.
    // Each file needs its own real tinyPng() call (CP-50 point 4): the hash-dedup hard block
    // would otherwise reject all but the first of 5 files sharing one buffer as duplicates.
    const names = Array.from({ length: 5 }, (_, i) => `e2e-media-bulk-${stamp}-${i}.png`);
    const files = await Promise.all(
      names.map(async (name) => ({ name, mimeType: "image/png" as const, buffer: await tinyPng() }))
    );

    // The grid's display name is a cosmetically generated string, unrelated to the uploaded
    // filename (see the test above) — collect each successful upload's real row id from its own
    // POST response instead of matching by name.
    const uploadedIds: Promise<string>[] = [];
    page.on("response", (res) => {
      if (res.url().includes("/api/v1/media") && res.request().method() === "POST" && res.ok()) {
        uploadedIds.push(res.json().then((body) => body.data.id as string));
      }
    });

    try {
      await page.locator('input[type="file"]').setInputFiles(files);
      await expect(grid).toHaveCount(before + 5, { timeout: 20_000 });
    } finally {
      // In a finally so a failed assertion above still cleans these up — a leaked upload here
      // would otherwise pollute every other e2e file's absolute-count assertions for the rest of
      // the run (the lesson CP-31 phase 3's post-editor.spec.ts leak already taught). Each
      // deletion waits for the grid to actually settle at the new, smaller count before the next
      // iteration checks for its own card: deleting one card invalidates the Media tag and
      // triggers a refetch, and checking the next id's card without waiting for that refetch to
      // land race-risked seeing a stale DOM and skipping a real, still-present card — confirmed as
      // the actual cause of one card leaking into the next test's count once.
      const ids = (await Promise.allSettled(uploadedIds))
        .filter((r): r is PromiseFulfilledResult<string> => r.status === "fulfilled")
        .map((r) => r.value);
      let remaining = before + ids.length;
      for (const id of ids) {
        const card = page.getByTestId(`media-card-${id}`);
        if (await card.count() > 0) {
          await card.locator("button").click();
          await page.getByTestId("confirm-modal-confirm").click();
          remaining -= 1;
          await expect(grid).toHaveCount(remaining, { timeout: 15_000 });
        }
      }
    }
  });

  test("search filters the grid to media whose display name matches, and un-filters when cleared", async ({
    page,
  }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();

    const [uploadResponse] = await Promise.all([
      page.waitForResponse(
        (res) => res.url().includes("/api/v1/media") && res.request().method() === "POST" && res.ok()
      ),
      page.locator('input[type="file"]').setInputFiles({
        name: `e2e-media-search-${Date.now()}.png`,
        mimeType: "image/png",
        buffer: await tinyPng(),
      }),
    ]);
    const uploaded = (await uploadResponse.json()).data as { id: string; displayName: string };
    await expect(grid).toHaveCount(before + 1, { timeout: 15_000 });

    const card = page.getByTestId(`media-card-${uploaded.id}`);
    // No seeded system_texts in the test DB, so t() falls back to the raw key — the same
    // convention every other admin e2e test already relies on (placeholder_search_tags, etc).
    const search = page.getByPlaceholder("placeholder_search_media");

    // The exact generated name, case-flipped partway through: proves both the partial-substring
    // match and the case-insensitivity in one query, without needing a planted marker (the real
    // name is server-generated and not client-controllable).
    const mixedCase = uploaded.displayName.slice(0, 3).toUpperCase() + uploaded.displayName.slice(3);
    await search.fill(mixedCase);
    await expect(card).toBeVisible({ timeout: 10_000 });

    // A search that can never match (display names are letters-only) hides it.
    await search.fill("zzz-not-a-real-match-9999");
    await expect(card).not.toBeVisible({ timeout: 10_000 });

    // Clearing the search brings the full grid back.
    await search.fill("");
    await expect(grid).toHaveCount(before + 1, { timeout: 10_000 });

    await card.locator("button").click();
    await page.getByTestId("confirm-modal-confirm").click();
    await expect(grid).toHaveCount(before, { timeout: 15_000 });
  });

  test("bulk select and delete: a protected card survives, the rest are removed", async ({ page }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();
    const admin = await adminContext(FILE_KEY);

    try {
      const uploadedIds: string[] = [];
      for (let i = 0; i < 2; i++) {
        const [uploadResponse] = await Promise.all([
          page.waitForResponse(
            (res) => res.url().includes("/api/v1/media") && res.request().method() === "POST" && res.ok()
          ),
          page.locator('input[type="file"]').setInputFiles({
            name: `e2e-media-bulk-${Date.now()}-${i}.png`,
            mimeType: "image/png",
            buffer: await tinyPng(),
          }),
        ]);
        uploadedIds.push((await uploadResponse.json()).data.id as string);
      }
      await expect(grid).toHaveCount(before + 2, { timeout: 15_000 });
      const [freeIdA, freeIdB] = uploadedIds;

      // A third media, attached to a published post as its poster through the real API — the same
      // in-use protection deleteMedia already enforces for a single delete must carry over to the
      // bulk path unchanged, never silently force-deleted.
      const protectedMediaRes = await admin.post("/api/v1/media", {
        multipart: { file: { name: "poster.png", mimeType: "image/png", buffer: await tinyPng() } },
      });
      const protectedMedia = (await protectedMediaRes.json()).data as { id: string };
      const post = await createPost(admin, { status: "Published", posterId: protectedMedia.id });

      try {
        await page.reload();
        await expect(grid).toHaveCount(before + 3, { timeout: 15_000 });

        await page.getByTestId(`media-select-${freeIdA}`).click();
        await page.getByTestId(`media-select-${freeIdB}`).click();
        await page.getByTestId(`media-select-${protectedMedia.id}`).click();

        const actionBar = page.getByTestId("bulk-action-bar");
        await expect(actionBar).toBeVisible();
        await expect(actionBar).toContainText("3");

        await page.getByTestId("bulk-delete-button").click();
        await page.getByTestId("confirm-modal-confirm").click();

        // Partial result: the two free cards are gone, the protected one survives untouched.
        await expect(page.getByTestId(`media-card-${freeIdA}`)).not.toBeVisible({ timeout: 15_000 });
        await expect(page.getByTestId(`media-card-${freeIdB}`)).not.toBeVisible();
        await expect(page.getByTestId(`media-card-${protectedMedia.id}`)).toBeVisible();
        await expect(grid).toHaveCount(before + 1, { timeout: 15_000 });

        // The page's own partial-result notification (this request is a 200 with a mixed
        // deleted/blocked body, not a rejection the global middleware would toast on its own) —
        // t() falls back to its raw key in this empty-system_texts test DB, so GlobalToaster shows
        // the notification's `details` text instead, which is where this real sentence comes from.
        await expect(page.getByText("skipped because they're used in a post", { exact: false })).toBeVisible();
      } finally {
        await post.cleanup();
        await admin.delete(`/api/v1/media/${protectedMedia.id}`);
      }
    } finally {
      await admin.dispose();
    }
  });

  // CP-50 point 4: binary-content hash dedup. A second upload of the exact same bytes (different
  // filename) is hard-blocked (409), surfaced in the upload-issues panel as a clickable label
  // naming the existing match — clicking it should jump the search box to find the original.
  test("re-uploading the same file's content shows a clickable duplicate label that jumps search to the original", async ({
    page,
  }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();
    const buffer = await tinyPng();

    const [firstUploadResponse] = await Promise.all([
      page.waitForResponse(
        (res) => res.url().includes("/api/v1/media") && res.request().method() === "POST" && res.ok()
      ),
      page.locator('input[type="file"]').setInputFiles({
        name: `e2e-media-dup-original-${Date.now()}.png`,
        mimeType: "image/png",
        buffer,
      }),
    ]);
    const original = (await firstUploadResponse.json()).data as { id: string; displayName: string };
    await expect(grid).toHaveCount(before + 1, { timeout: 15_000 });

    const duplicateName = `e2e-media-dup-copy-${Date.now()}.png`;
    await page.locator('input[type="file"]').setInputFiles({
      name: duplicateName,
      mimeType: "image/png",
      buffer, // same bytes as the first upload
    });

    // No-op upload: the grid never grows past the one real row created above.
    await page.waitForTimeout(1000);
    await expect(grid).toHaveCount(before + 1);

    // t() falls back to its raw key in this empty-system_texts test DB (same convention every
    // other admin e2e test relies on) — "upload_issues"/"duplicate_of" are the literal fallbacks.
    const issuesPanel = page.getByText("upload_issues");
    await expect(issuesPanel).toBeVisible({ timeout: 10_000 });
    const duplicateLabel = page.getByRole("button", { name: new RegExp(duplicateName) });
    await expect(duplicateLabel).toBeVisible();
    await expect(duplicateLabel).toContainText("duplicate_of");
    await expect(duplicateLabel).toContainText(original.displayName);

    const search = page.getByPlaceholder("placeholder_search_media");
    await duplicateLabel.click();
    await expect(search).toHaveValue(original.displayName);
    await expect(page.getByTestId(`media-card-${original.id}`)).toBeVisible({ timeout: 10_000 });
    await expect(grid).toHaveCount(1, { timeout: 10_000 });

    await search.fill("");
    const card = page.getByTestId(`media-card-${original.id}`);
    await card.locator("button").click();
    await page.getByTestId("confirm-modal-confirm").click();
    await expect(grid).toHaveCount(before, { timeout: 15_000 });
  });

  test("selecting more files than NEXT_PUBLIC_MAX_FILES_PER_UPLOAD rejects the whole batch up front", async ({
    page,
  }) => {
    const grid = page.locator("div.group.relative.bg-card");
    const before = await grid.count();

    const buffer = await tinyPng();
    const tooMany = Array.from({ length: 31 }, (_, i) => ({
      name: `e2e-media-cap-${i}.png`,
      mimeType: "image/png" as const,
      buffer,
    }));

    await page.locator('input[type="file"]').setInputFiles(tooMany);

    // Nothing should upload — the client-side cap rejects before any request fires.
    await page.waitForTimeout(1000);
    await expect(grid).toHaveCount(before);
  });
});
